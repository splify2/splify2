#!/bin/sh
# Общее для программ плагина lists-catalog: пути, настройки, скачивание, разбор каталога, свои списки.
#
# Подключается точкой из bin/lists, bin/update-lists и hooks/*. Каркасу плагин принадлежит только через его
# API: библиотека `$SPLIFY2_LIB` (jshn, s2_fail, s2_setting) и службы хоста `$SPLIFY2_HOST` (скачивание, спека,
# применение, режим туннеля, настройки). Файлов и переменных каркаса здесь нет — каталог списков и программу ядра
# хост называет сам (`splify2-host paths`).
. "${SPLIFY2_LIB:?программа запускается хостом splify2 (нет SPLIFY2_LIB)}"

# Рабочие файлы плагина: настройки и кэш каталога живут в conf (сохраняются всегда), то, что не должно пережить
# перезагрузку, — в STEER_PLUGIN_STATE (память, закрытый каталог).
CONF_DIR="${STEER_PLUGIN_CONF:?нет STEER_PLUGIN_CONF}"
RUN_DIR="${STEER_PLUGIN_STATE:?нет STEER_PLUGIN_STATE}"
# Кэш каталога списков и отметки версий второго издателя. Каталог, скачанный раз, переживает перезагрузку: без него
# вкладка каталога пуста, пока роутер не дотянется до издателя.
CATALOG_FILE="$CONF_DIR/manifest.json"
# Свои списки лежат отдельным подкаталогом каталога списков, а не вперемешку со списками издателя.
#
# Иначе их не отличить: local_lists отдаёт всё, что лежит на диске, и «мой файл» от «файла из каталога» отличался бы
# только тем, есть ли такое имя в каталоге, — то есть менялся бы сам по себе при обновлении каталога.
CUSTOM_DIR=custom
# Предел размера своего списка. Не перестраховка: на роутере с маленьким флешем список, который туда не влезет,
# положит не только себя. Мегабайта хватает на ~70 тысяч доменов — для ручного списка заведомо достаточно.
LIST_MAX_BYTES=1048576
# По сколько байт отдавать список обратно (list_get). ubus не резиновый, а свой список разрешён до LIST_MAX_BYTES —
# целиком он в одно сообщение не влезает. Кусок приезжает байт в байт, смещение считается по считанному.
LIST_CHUNK="${LIST_CHUNK:-16384}"
# Сколько записей списка показывает list_peek («глазик» у списка в правиле).
PEEK_LINES="${PEEK_LINES:-300}"

# Каталог списков и программа ядра — ресурсы ядра, и называет их хост. Один вызов на программу.
lists_init() {
    [ -n "${LISTS_DIR:-}" ] && return 0
    _li="$("$SPLIFY2_HOST" paths)" || s2_fail "хост не назвал каталог списков"
    json_load "$_li" 2>/dev/null || s2_fail "хост ответил не по форме"
    json_get_var LISTS_DIR lists
    json_get_var STEER_BIN steer
    [ -n "$LISTS_DIR" ] || s2_fail "хост не назвал каталог списков"
}

# Скачать ссылку в файл с обходом закрытого издателя — службой хоста. Сначала во временный файл, потом переименование:
# оборванная загрузка не оставляет на месте рабочего списка обрубок. FETCH_NOTE — каким путём приехало или почему не
# вышло. Код 0 — файл на месте.
fetch_file() {  # URL ФАЙЛ  (срок — FETCH_TIMEOUT_S, пусто — умолчание хоста)
    FETCH_NOTE=""
    _ff_out="$("$SPLIFY2_HOST" fetch "$1" "$2" ${FETCH_TIMEOUT_S:+--timeout "$FETCH_TIMEOUT_S"} 2>/dev/null)"
    _ff_rc=$?
    json_load "$_ff_out" 2>/dev/null && json_get_var FETCH_NOTE note
    return "$_ff_rc"
}

# Адрес каталога: настройка человека, а пусто — умолчание схемы.
catalog_url() {
    s2_setting manifest_url
}
# Умолчание схемы настроек — из её же файла: второе написание адреса разошлось бы с первым в день, когда его меняют.
catalog_url_default() {
    jsonfilter -i "${STEER_PLUGIN_DIR:?}/settings.schema.json" -e '@.properties.manifest_url.default' 2>/dev/null
}

# Найти файл списка в манифесте по id И ВИДУ.
#
# Вид обязателен, и это не перестраховка: `categories` и `domain_lists` — разные
# пространства имён, и один id законно есть в обоих. У издателя так с `hodca` и `news`:
# адресный `hodca.lst` (5444 подсети) и доменный `domains/hodca.lst` (250 имён).
#
# Прежняя версия искала сначала в доменных, поэтому на запрос АДРЕСНОЙ категории скачивала
# доменный файл. Дальше канал читал домены как подсети, nft отвергал набор целиком — и
# вставала вся маршрутизация. Симптом «включил Хостинги и CDN, всё умерло» — отсюда.
manifest_file() {  # ID ВИД
    case "$2" in
        domains)  jsonfilter -i "$CATALOG_FILE" -e "@.domain_lists[@.id='$1'].file" 2>/dev/null ;;
        prefixes) jsonfilter -i "$CATALOG_FILE" -e "@.categories[@.id='$1'].file" 2>/dev/null ;;
        *)
            # Вид не указан — старый вызов. Тогда порядок обратный прежнему: адресные
            # первыми, потому что доменные лежат в своём подкаталоге и путь у них
            # различим, а вот адресная категория при промахе давала именно ту поломку.
            f="$(jsonfilter -i "$CATALOG_FILE" -e "@.categories[@.id='$1'].file" 2>/dev/null)"
            [ -n "$f" ] || f="$(jsonfilter -i "$CATALOG_FILE" -e "@.domain_lists[@.id='$1'].file" 2>/dev/null)"
            printf '%s' "$f"
            ;;
    esac
}

# Поле записи манифеста — по id и виду. Тем же запросом, что manifest_file, и рядом с ним:
# два места, знающие, где в манифесте лежит категория, разошлись бы при первой же правке
# формата.
#
# Понадобилось, когда каталог научился называть НАБОРЫ (`format: "srs"`, своя `url`): такая
# запись описывает не «файл по base_url», а «скачай вот это и разложи движком». Отличить
# одно от другого можно только полем, и читать его должен тот же код, что читает путь.
manifest_field() {  # ID ВИД КЛЮЧ
    case "$2" in
        domains)  jsonfilter -i "$CATALOG_FILE" -e "@.domain_lists[@.id='$1'].$3" 2>/dev/null ;;
        prefixes) jsonfilter -i "$CATALOG_FILE" -e "@.categories[@.id='$1'].$3" 2>/dev/null ;;
    esac
}

# Путь второй половины набора: у одной ссылки бывает две записи — подсети и домены. Ищется
# ПО ССЫЛКЕ, а не по id: id у половин разные (у доменной он с приставкой `svc_`), а набор
# один и тот же, и скачивать его дважды незачем.
manifest_file_by_url() {  # ССЫЛКА ВИД
    case "$2" in
        domains)  jsonfilter -i "$CATALOG_FILE" -e "@.domain_lists[@.url='$1'].file" 2>/dev/null | head -1 ;;
        prefixes) jsonfilter -i "$CATALOG_FILE" -e "@.categories[@.url='$1'].file" 2>/dev/null | head -1 ;;
    esac
}

# Локальный путь списка: ПОВТОРЯЕТ путь у издателя, а не берёт от него имя файла.
#
# `basename` схлопывал `hodca.lst` и `domains/hodca.lst` в один локальный файл, и они
# затирали друг друга. То же правило продублировано в интерфейсе (pathFor) — разойдясь,
# они дадут «список скачан, а канал его не находит».
#
# ПУТЬ ПРИХОДИТ ИЗ ИНТЕРНЕТА, и проверяется он здесь, в единственном месте, где
# собирается. Поле `file` берётся из манифеста издателя (адрес которого вдобавок
# переопределяется через uci), а срезание ведущих слэшей от `..` не спасает: `file` вида
# `../../../etc/crontabs/root` давал запись файла ОТ ROOT куда угодно, содержимым с того
# же издателя, — крон, rc.local, сам этот скрипт. Тем же путём list_remove удалял любой
# файл: проверка «занят каналом» сравнивала уже подменённый путь.
#
# Для СВОИХ списков эта мысль додумана давно (см. list_put: «без этого ../../etc/passwd
# было бы законным именем»), а для чужих — нет, хотя чужой источник доверия заслуживает
# меньше. Правило одно на оба случая: имя может состоять только из безопасных символов,
# и ни одна его часть не может быть «..».
# Возвращает НЕНУЛЕВОЙ код на негодном пути, а не зовёт fail сама, и это важно: её
# вызывают в подстановке `$( )`, то есть в подоболочке, где exit из fail завершил бы
# только подоболочку. Ответ об ошибке ушёл бы в переменную вместо клиента, а скрипт
# спокойно продолжил бы работу с этой строкой как с путём. Поэтому решение принимает
# вызывающий: `dest="$(local_path "$f")" || fail ...`.
local_path() {  # ПУТЬ_У_ИЗДАТЕЛЯ
    rel="$(echo "$1" | sed 's|^/*||')"
    case "$rel" in
        ''|.|..|*/../*|*/..|../*|*//*) return 1 ;;
        *[!A-Za-z0-9_./-]*)            return 1 ;;
    esac
    printf '%s/%s' "$LISTS_DIR" "$rel"
}


# Путь своего списка. Доменные лежат в подкаталоге, адресные — рядом, как у издателя.
custom_path() {  # ИМЯ ВИД
    case "$2" in
        domains) printf '%s/%s/domains/%s.lst' "$LISTS_DIR" "$CUSTOM_DIR" "$1" ;;
        *)       printf '%s/%s/%s.lst'         "$LISTS_DIR" "$CUSTOM_DIR" "$1" ;;
    esac
}

# ОТКУДА ВЗЯЛСЯ СВОЙ СПИСОК — рядом с ним, отдельным файлом.
#
# ЗАЧЕМ. Завести список можно тремя способами: набрать записи руками, выбрать файл, дать
# ссылку. Изменить его после этого было НЕЧЕМ: единственная кнопка рядом со списком —
# удалить и завести заново. А правка нужна ровно по тому же разделению, каким список
# завели: у файла меняют файл, у ссылки — ссылку, у набранного руками — сами записи. Не зная
# происхождения, интерфейс вынужден предлагать все три способа всем, и человек, положивший
# файл на 20 тысяч строк, получает предложение отредактировать его в текстовом поле.
#
# ПОЧЕМУ ФАЙЛОМ, А НЕ В uci. Список — это файл на диске, и его происхождение обязано
# лежать там же: список, положенный руками в /etc/steer/lists/custom, и его запись в uci
# разошлись бы при первом же `rm`. Плюс так происхождение переживает то же, что и сам
# список, и теряется вместе с ним, а не отдельно.
#
# ФОРМАТ — «ключ=значение» по строке, как у SUB_INFO: разбирается тем же `while read`, а
# вторая реализация разбора JSON в оболочке не нужна ни здесь, ни там.
#
# Расширение НЕ «.lst»: `local_lists` и сборка архива обходят каталог по `*.lst`, и файл
# происхождения, попавший в эту выборку, стал бы виден как ещё один список — с записями
# вида «source=file», которые санитайзер отбросит все до одной.
custom_meta_path() {  # ИМЯ ВИД
    printf '%s.src' "$(custom_path "$1" "$2")"
}

# Чужой текст на входе движка. Проверяется ЗДЕСЬ, а не в интерфейсе: интерфейс можно
# обойти, а последствие непроверенного списка молчаливое — спека применится, nft отвергнет
# набор, и канал останется пустым без единого слова о причине.
#
# Что делаем с почти-верным: одиночный адрес дополняем до /32 (человек пишет 1.2.3.4, имея
# в виду именно его), домены приводим к нижнему регистру и снимаем ведущее «*.» — то есть
# принимаем распространённые записи вместо того, чтобы отвергать их из принципа. Что
# отбросили — считаем и говорим числом: молчаливая потеря строк здесь была бы худшим из
# возможных поведений.
sanitize_list() {  # ВИД ВХОД ВЫХОД ФАЙЛ_СЧЁТЧИКОВ
    awk -v kind="$1" -v stat="$4" '
    # Октет 0..255 и длина префикса 0..32 — то, чего не выражает регулярное выражение.
    function ip_ok(a,   p, i) {
        split(a, p, ".")
        for (i = 1; i <= 4; i++) if (p[i] + 0 > 255 || p[i] == "" || length(p[i]) > 3) return 0
        return 1
    }
    function cidr_ok(a,   q) {
        split(a, q, "/")
        if (!ip_ok(q[1])) return 0
        return (q[2] + 0 <= 32 && q[2] != "" && length(q[2]) <= 2)
    }
    {
        line = $0
        sub(/\r$/, "", line)
        sub(/#.*/, "", line)
        gsub(/^[ \t]+|[ \t]+$/, "", line)
        if (line == "") next
        if (kind == "prefixes") {
            # Проверяются и ДИАПАЗОНЫ значений, а не только форма. Раньше «10.0.0.256» и
            # «192.168.0.0/40» проходили как верные, движок их тоже пропускает (он смотрит
            # только на цифры, точки и слэши), и отвергал их уже nft — целиком весь
            # ruleset одной транзакцией, сообщением про синтаксис nft. Человек при этом
            # видел «Список «x»: строк 12» и не знал, какая строка виновата.
            if (line ~ /^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$/)         { if (ip_ok(line))       { print line "/32"; ok++; next } bad++; next }
            if (line ~ /^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+\/[0-9]+$/) { if (cidr_ok(line))     { print line;       ok++; next } bad++; next }
            bad++; next
        }
        line = tolower(line)
        sub(/^\*\./, "", line)
        sub(/\.$/, "", line)
        if (line ~ /^[a-z0-9]([a-z0-9._-]*[a-z0-9])?$/ && line ~ /\./) { print line; ok++; next }
        bad++
    }
    END { printf "%d %d\n", ok+0, bad+0 > stat }
    ' "$2" > "$3"
}


# ---- свои списки в архиве настроек (хук backup_sections) -----------------------------------------------------------
# Имя раздела архива — [A-Za-z0-9_]+, имя своего списка — [A-Za-z0-9_-]+: дефис кодируется, подчёркивание удваивается
# (`_` → `__`, `-` → `_d`). Кодировка однозначна: за `_` всегда идёт `_` или `d`.
sec_enc() {  # ИМЯ_СПИСКА
    printf '%s' "$1" | sed -e 's/_/__/g' -e 's/-/_d/g'
}
sec_dec() {  # ИМЯ_РАЗДЕЛА
    _sd_m="$(printf '\001')"
    printf '%s' "$1" | sed -e "s/__/$_sd_m/g" -e 's/_d/-/g' -e "s/$_sd_m/_/g"
}

# Значение настройки плагина из архива: ключ из схемы и значение, которое схема примет. Пишет их хост, но отказ до записи
# нужен раньше — архив проверяется целиком до первой записи.
setting_value_ok() {  # КЛЮЧ ЗНАЧЕНИЕ
    case "$1" in
        manifest_url)
            case "$2" in http://*|https://*) ;; *) return 1 ;; esac
            case "$2" in *[\ \"\'\`\$\|\<\>]*) return 1 ;; esac ;;
        list_shrink_factor)
            case "$2" in ''|*[!0-9]*) return 1 ;; esac ;;
        allow_domains_tag)
            case "$2" in ''|*[!A-Za-z0-9_.-]*) return 1 ;; esac ;;
        *) return 1 ;;
    esac
    return 0
}
