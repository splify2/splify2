import { useEffect, useState } from 'react'
import { pending } from '@/lib/pending'
import type { Spec } from '@/lib/model'

/** Спека для раздела, который правит её на месте.
 *
 *  У такого раздела своя копия в состоянии — правка видна на экране сразу, — а в хранилище она уходит
 *  через `pending.edit`. Правка вырастает из ЭТОЙ копии: раздел собирает следующую спеку из той, что
 *  у него в руках, и хранилище записывает её целиком.
 *
 *  Хранилище при этом само подменяет спеку — не по правке человека, а по тому, что лежит на роутере
 *  после применения (apply мог переписать файл: самолечение вставляет выходам `ipv6`). Копия раздела
 *  обязана подхватить подмену, иначе первая же его правка после «Применить» записала бы поверх
 *  роутерной спеки прежнюю — с утраченными ключами и без правок, сделанных в других разделах.
 *
 *  Загрузка — общая (`pending.load`: кто пришёл раньше, тот и загрузил), отказ загрузки даёт `null`. */
export function useSpecCopy() {
    const [spec, setSpec] = useState<Spec | null>(null)
    useEffect(() => {
        pending.load().then(setSpec).catch(() => setSpec(null))
        return pending.onReplaced(setSpec)
    }, [])
    return [spec, setSpec] as const
}
