/** ПРЕДЕЛ ОДНОВРЕМЕННЫХ ПРОВЕРОК УЗЛОВ — ТРИ, и это не «побольше, чтобы быстрее»: каждая проверка
 *  поднимает через ядро настоящее соединение до узла и меряет по нему время ответа, а
 *  роутер однопроцессорный и с одним каналом наружу. По одному — тридцать нажатий с
 *  ожиданием; все сразу — замер собственной очереди на том же процессоре, а не задержки
 *  узла. Один узел за вызов сделано намеренно: проверка упирается в таймаут, а вызов ubus
 *  столько не живёт. */
export const PROBE_LIMIT = 3

/** Цвет отклика: до 150 мс — хорошо, до 400 — обычно, дальше — заметно. */
export function latencyTone(ms: number): 'good' | 'ok' | 'slow' {
    return ms < 150 ? 'good' : ms < 400 ? 'ok' : 'slow'
}

/** Задержка ответившего узла. VLESS меряет ответ через туннель (`ttfb_ms`), hysteria2 и прокси
 *  steer-proxy — рукопожатие с запросом (`handshake_ms`), а `ttfb_ms` у них всегда -1: по нему
 *  исправный узел показывался как «-1 мс». */
export function probeMs(p: { ttfb_ms: number; handshake_ms: number }): number {
    return p.ttfb_ms >= 0 ? p.ttfb_ms : p.handshake_ms
}
