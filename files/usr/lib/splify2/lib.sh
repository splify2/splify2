#!/bin/sh
# Библиотека для shell-плагинов (splify2-api v1, plugin-sdk/docs/splify2-api.md, «Библиотека»).
#
# Программа плагина подключает её одной строкой:
#
#     . "$SPLIFY2_LIB"
#
# и получает три вещи: jshn (libubox: json_init, json_add_string, json_load …), `s2_fail` и `s2_setting`. Всё, что
# принадлежит каркасу — скачивание, спека, настройки каркаса, применение, — плагин берёт у служб хоста
# (`"$SPLIFY2_HOST" …`, раздел «Службы хоста»), а не из файлов и переменных каркаса: их состав не обещан и меняется.
#
# Файл не печатает и не завершает процесс при подключении. Версия API — SPLIFY2_API (1).

. "${JSHN_SH:-/usr/share/libubox/jshn.sh}"

# Отказ метода rpc плагина: объект {"ok":false,"error":"…"} в stdout и выход с кодом 0 (код не 0 хост считает падением
# программы, а не ответом).
s2_fail() {  # ТЕКСТ
    json_init
    json_add_boolean ok 0
    json_add_string error "$1"
    json_dump
    exit 0
}

# Значение настройки плагина (то, что человек задал в форме по схеме, а если не задал — умолчание схемы).
# Печатает значение; код 1 и пустая строка — значения нет ни там, ни там.
s2_setting() {  # КЛЮЧ
    "$SPLIFY2_HOST" settings get "$1"
}
