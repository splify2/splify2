#!/bin/sh
# Часть объекта rpcd splify2 — подключается диспетчером /usr/libexec/rpcd/splify2 по имени
# метода. ЗАЧЕМ ФАЙЛОВ НЕСКОЛЬКО. busybox ash разбирает файл целиком, и объект в 4500 строк
# стоил 110 мс разбора на КАЖДЫЙ вызов — при том, что сам ответ считается за 30-90 мс.
# Диспетчер разбирает только себя, общие помощники (common.sh) и группу вызванного метода.
# Переменные и швы для стендов объявлены в диспетчере и здесь доступны как есть.


# Помощники, нужные больше чем одной группе методов (и блоку list).


# Файл в /tmp годится для чтения обратно, только если он НАШ. /tmp на роутере пишут все
# процессы, включая непривилегированные (nobody, dnsmasq, logd), а имена наших файлов там
# предсказуемы: чужой файл на месте нашей памяти — это чужие данные в ответе интерфейсу, а
# до правки gh_load — и чужой код от root. Проверяется владелец, не права: права файла
# можно сделать любыми, владельца — нет.
#
# Владелец — из `ls -ln`, а не из stat: busybox OpenWrt по умолчанию собран без stat (25.12.5 —
# «stat: not found»), и проверка через него на таком роутере считала чужим КАЖДЫЙ файл —
# архив настроек не выгружался и не восстанавливался вовсе, кэши не читались. `ls` есть всегда.
own_file() {  # ПУТЬ
    [ -f "$1" ] || return 1
    set -- $(ls -ldn "$1" 2>/dev/null)
    [ -n "${3:-}" ] && [ "$3" = "$(id -u 2>/dev/null)" ]
}

# Наш и закрытый от всех (0600): для файлов с приватными ключами (архив настроек). Права —
# тоже из `ls -ln`, по той же причине, что владелец.
private_file() {  # ПУТЬ
    own_file "$1" || return 1
    set -- $(ls -ldn "$1" 2>/dev/null)
    [ "${1:-}" = "-rw-------" ]
}

# Имя подписки в виде, годном и для имени файла, и для имени секции uci: латиница, цифры и
# подчёркивание. Дефис уходит тоже — uci имён с ним не принимает.
sub_slug() {
    _ss_in="${1:-}"
    _ss_lat="$(printf '%s' "$_ss_in" | tr -c 'A-Za-z0-9_' '_' | cut -c1-24 | sed 's/_*$//')"
    # Имя не латиницей («Дом», «Работа») или без единого годного знака: латинская часть таких
    # имён не различает — tr побайтно превращал каждый байт UTF-8 в подчёркивание, sed снимал
    # хвост, оставалась пустота, и sub_use подставлял main. То есть вторая подписка человека
    # молча ПЕРЕЗАПИСЫВАЛА основную, а sub_del по такому имени удалял её. Хвост из хеша имени
    # делает такие имена различимыми и устойчивыми; латинские имена не меняются — у людей уже
    # лежат файлы под прежними именами.
    if [ -n "$_ss_in" ] && { [ -z "$_ss_lat" ] ||
            [ -n "$(printf '%s' "$_ss_in" | LC_ALL=C tr -d '\000-\177')" ]; }; then
        _ss_h="$(printf '%s' "$_ss_in" | md5sum | cut -c1-8)"
        _ss_lat="$(printf '%s' "$_ss_lat" | cut -c1-15)"
        printf '%s%sh%s' "$_ss_lat" "${_ss_lat:+_}" "$_ss_h"
    else
        printf '%s' "$_ss_lat"
    fi
}

# Переставить SUB и SUB_INFO на нужную подписку. После вызова ВСЕ помощники (sub_fetch,
# sub_quota_ask, sub_userinfo_emit) работают с ней и ни о чём не знают — в этом и смысл:
# «какая подписка выбрана» решается в одном месте, а движку пути называются явно.
sub_use() {
    SUB_NAME="$(sub_slug "${1:-main}")"
    [ -n "$SUB_NAME" ] || SUB_NAME=main
    if [ "$SUB_NAME" = main ]; then
        SUB="${SUB_MAIN:-/etc/steer/sub.txt}"
    else
        SUB="$SUBS_DIR/$SUB_NAME.txt"
    fi
    SUB_INFO="${SUB%.txt}.userinfo"
}

# Все подписки роутера: первая и заведённые после неё. Перечень собирается из uci, а файлы
# лишь дополняют его — подписка, чей файл скачан, но ключ потерян, всё равно должна быть
# видна, иначе её нельзя ни обновить, ни удалить.
sub_names() {
    { [ -s "${SUB_MAIN:-/etc/steer/sub.txt}" ] || [ -n "$(uci -q get splify2.main.sub_url)" ] && echo main
      uci -q show splify2 2>/dev/null | sed -n "s/^splify2\.sub_\([A-Za-z0-9_]*\)=subscription$/\1/p"
      [ -d "$SUBS_DIR" ] && for _f in "$SUBS_DIR"/*.txt; do
          [ -e "$_f" ] || continue
          _b="${_f##*/}"; printf '%s\n' "${_b%.txt}"
      done
    } 2>/dev/null | awk 'NF && !seen[$0]++'
}

# Проверить спеку движком, ничего не меняя: `steer check`. Печатает причину отказа (или
# предупреждения движка) в stdout, код возврата 0 — спека годна.
#
# Почему не просто `apply --dry-run`. Dry-run не чисто читающий — он раздаёт выходам метки в
# реестре состояния, и проверка, идущая одновременно с чужим apply демона, писала бы реестр
# посреди его применения. Команда check демона встаёт в ту же очередь, что apply и reload, и
# гонки нет. Демона нет (сокета нет или он не отвечает) — проверяем тем же dry-run напрямую:
# на роутере без запущенного движка сохранение не должно становиться невозможным.
# Ответ демона — одна строка JSON: code (код dry-run) и stderr (причина); error/message — отказ
# самого демона, тогда проверка не состоялась, и падаем обратно на прямой dry-run.
engine_check() {
    local spec="$1" sock="${STEER_SOCK:-/etc/steer/steer.sock}" resp code msg
    if [ -e "$sock" ]; then
        if resp="$("$STEER" ctl check <"$spec" 2>/dev/null)" && [ -n "$resp" ] \
            && [ -z "$(printf '%s' "$resp" | jsonfilter -q -e '@.error' 2>/dev/null)" ]; then
            code="$(printf '%s' "$resp" | jsonfilter -q -e '@.code' 2>/dev/null)"
            if [ -n "$code" ]; then
                [ "$code" = 0 ] && return 0
                printf '%s' "$resp" | jsonfilter -q -e '@.stderr' 2>/dev/null
                return 1
            fi
        fi
    fi
    msg="$("$STEER" apply --dry-run --spec "$spec" 2>&1 >/dev/null)" || { printf '%s' "$msg"; return 1; }
    return 0
}

# ЧТЕНИЕ СПЕКИ ИЗ ОБОЛОЧКИ. Интерфейс пишет спеку v2 (JSON с `"version": 2`), но до первого
# сохранения на диске может лежать прежняя v1 (`schema`, `channels`, `sub_file`), поэтому все
# читатели ниже понимают обе формы; разбор самой спеки — дело движка и интерфейса.

# Файл подписки выхода: v2 — `subscription`, v1 — `sub_file`.
spec_out_sub() {  # ИМЯ_ВЫХОДА -> путь
    _sos="$(jsonfilter -i "$(spec_json)" -e "@.outputs['$1'].subscription" 2>/dev/null)"
    [ -n "$_sos" ] || _sos="$(jsonfilter -i "$(spec_json)" -e "@.outputs['$1'].sub_file" 2>/dev/null)"
    printf '%s' "$_sos"
}

# Попросить демон движка перечитать спеку и подписки: помощник выхода (клиент VLESS или
# hysteria2) читает файл подписки при подъёме, а подпись помощника включает его содержимое, так
# что `steer reload` перезапускает ровно тех, чья подписка изменилась. Раньше для этого
# слали сигналы экземплярам procd `vless_<выход>`; таких экземпляров с 1.8 нет.
#
# ТОЛЬКО ЕСЛИ СОХРАНЁННОЕ РАВНО ПРИМЕНЁННОМУ. `reload` применяет спеку с диска целиком, а
# интерфейс сохраняет правки сразу и применяет их само, через долю секунды тишины (автоприменение): перезагрузка
# по расписанию обновления подписки применила бы чужие неприменённые правки втихую и рассинхронизила
# бы счётчик со снимком. Расхождение — не потеря: ближайшее «Применить» перезапустит помощника,
# потому что содержимое файла подписки и так входит в его подпись. Код 0 — перезагрузка была.
engine_reload_clean() {
    [ -x "$STEER" ] || return 1
    if [ -s "$APPLIED" ] && ! cmp -s "$(spec_json)" "$APPLIED" 2>/dev/null; then
        return 1
    fi
    "$STEER" reload --spec "$SPEC" >/dev/null 2>&1
}

# Файл настроек и секция main в нём: без секции `uci set splify2.main.X` отвечает «Entry not
# found», и запись молча не происходит (так было на роутере, где файл удалили руками).
uci_file() {
    if [ ! -f "$UCI_SPLIFY2" ]; then
        mkdir -p "$(dirname "$UCI_SPLIFY2")" 2>/dev/null
        touch "$UCI_SPLIFY2" 2>/dev/null
        [ -f "$UCI_SPLIFY2" ] || return 1
    fi
    uci -q get splify2.main >/dev/null 2>&1 || uci -q set splify2.main=splify2
}

# Записать настройку на флеш. Отказ `uci commit` (кончилось место, испорченный файл) — отказ метода, а не
# «ok»: иначе страница показывала бы сохранённое то, что после перезагрузки исчезнет.
uci_commit() {
    uci -q commit splify2 || fail_code disk.setting_not_saved "The setting was not saved. Free up some flash space and try again."
}

# Устройства выходов перечисленных видов. Имена спрашиваются у движка флагом --devices, а не
# берутся как имена выходов: устройство выводится из имени выхода, НО может быть задано в спеке
# явно, и тогда «имя выхода» — это молча неверный список ровно там, где по нему настраивают
# фаервол. kind=direct отсеивается сам: устройства у него нет, и --devices ничего не печатает.
fw_devices_of() {  # ВИДЫ_ЧЕРЕЗ_ЗАПЯТУЮ
    for k in $(printf '%s' "$1" | tr ',' ' '); do
        "$STEER" outputs --kind "$k" --devices --spec "$SPEC" 2>/dev/null
    done | grep . | sort -u
}

# ---- АДРЕС IPv6 У УСТРОЙСТВА ВЫХОДА: ЧТО ПИСАТЬ КЛЮЧУ `ipv6` --------------------------------------
#
# Ключ `ipv6: nat` ядро ставит выходу, у которого на самом устройстве есть адрес IPv6: у пира WARP
# он один, клиенты LAN сидят на ULA, и подменять их адрес есть чем. У туннеля с одним IPv4 (WireGuard
# без адреса IPv6) подменять нечем, и diag ядра отвечает на такой выход с `nat` отказом «у X нет
# адреса IPv6» — вместо жёлтого «нет masquerade IPv6», которым выход был без ключа. А у LAN почти
# всегда есть ULA, так что отказ получил бы почти каждый туннель без IPv6. Поэтому ключ зависит от
# устройства, и решает это одно место — для самолечения спеки (spec_heal_ipv6) и для перечня
# устройств (`devices`: панель пишет новому выходу то же самое):
#   nat   — у устройства есть адрес IPv6 области global (ULA тоже: так считает ядро, dev_has_v6 в
#           diag.c) либо сейчас, либо записанный в настройке сети его интерфейса (addresses, ip6addr);
#   off   — адреса нет: выход IPv6 не несёт, клиенты идут по IPv4;
#   пусто — решать не нам: у интерфейса задан ip6prefix (человек раздаёт клиентам префикс туннеля,
#           `ipv6: routed` он пишет сам) либо устройства нет и о нём ничего не известно.
#
# Таблица «УСТРОЙСТВО РЕЖИМ» (режим: nat, off или keep — «не трогать») собирается одним проходом:
# живые адреса (`ip -6 -o addr show` — один запуск на все устройства) и настройка сети (`uci show
# network`: интерфейс называет устройство опцией device/ifname, а без неё — собой, так у WireGuard
# и AmneziaWG). Живой адрес перекрывает настройку, `keep` — только `off`. Один запуск на таблицу, а не
# на устройство: `devices` спрашивают с шести экранов, и каждый лишний процесс на слабом роутере —
# это миллисекунды на каждый показ.
net_v6_table() {
    { ip -6 -o addr show 2>/dev/null; echo '@@'; uci -q show network 2>/dev/null; } | awk '
        function rank(m) { return m == "nat" ? 3 : (m == "keep" ? 2 : 1) }
        function put(d, m) {
            if (d == "") return
            if (!(d in best)) { ord[++no] = d; best[d] = m }
            else if (rank(m) > rank(best[d])) best[d] = m
        }
        $0 == "@@" { part = 2; next }
        part != 2 {
            # «5: wg0    inet6 fd00::2/64 scope global ...»; имя бывает с «@пир» на конце.
            if ($3 != "inet6") next
            for (i = 4; i < NF; i++)
                if ($i == "scope") {
                    if ($(i + 1) == "global") { d = $2; sub(/@.*/, "", d); sub(/:$/, "", d); put(d, "nat") }
                    break
                }
            next
        }
        {
            eq = index($0, "=")
            if (!eq) next
            key = substr($0, 1, eq - 1); val = substr($0, eq + 1)
            n = split(key, p, ".")
            if (p[1] != "network" || p[2] ~ /^@/) next
            if (n == 2) { if (val == "interface" && !(p[2] in isif)) { isif[p[2]] = 1; sec[++ns] = p[2] } next }
            if (n != 3) next
            gsub("\047", "", val)
            if (p[3] == "device" || p[3] == "ifname") dev[p[2]] = dev[p[2]] " " val
            else if (p[3] == "addresses" || p[3] == "ip6addr") adr[p[2]] = adr[p[2]] " " val
            else if (p[3] == "ip6prefix") pfx[p[2]] = 1
            else if (p[3] == "proto") proto[p[2]] = val
        }
        END {
            for (k = 1; k <= ns; k++) {
                s = sec[k]; m = "off"
                nt = split(adr[s], t, " ")
                # fe80::/10 — не адрес выхода, а служебный: global он не область.
                for (i = 1; i <= nt; i++)
                    if (t[i] ~ /:/ && t[i] !~ /^[Ff][Ee][89AaBb][0-9A-Fa-f]:/) m = "nat"
                if (m == "off" && pfx[s]) m = "keep"
                # Адрес придёт позже (DHCPv6, туннель 6in4/6to4/6rd): сейчас его нет, но «off» навсегда
                # оставил бы такое устройство без IPv6 через выход — решать не нам, как с ip6prefix.
                if (m == "off" && proto[s] ~ /^(dhcpv6|6in4|6to4|6rd)$/) m = "keep"
                nd = split(dev[s], dv, " ")
                if (nd) { for (i = 1; i <= nd; i++) put(dv[i], m) }
                else put(s, m)
            }
            for (k = 1; k <= no; k++) print ord[k], best[ord[k]]
        }'
}

v6_table_get() {  # УСТРОЙСТВО ТАБЛИЦА -> режим из таблицы; пусто — устройства в ней нет
    while read -r _vt_d _vt_m; do
        [ "$_vt_d" = "$1" ] && { printf '%s' "$_vt_m"; return 0; }
    done <<EOF
$2
EOF
}

# Что писать ключу ipv6 выхода-интерфейса на этом устройстве: nat, off или пусто (см. выше).
# Третий аргумент — файл настройки AmneziaWG у выхода kind=awg: устройство такого выхода заводит
# само ядро при apply, а лечение идёт ДО него, и по устройству адреса ещё не увидеть — он записан
# в строках Address файла.
v6_mode_of_dev() {  # ТАБЛИЦА УСТРОЙСТВО [ФАЙЛ_AWG] -> nat | off | пусто
    _vm_t="$(v6_table_get "$2" "$1")"
    [ "$_vm_t" = nat ] && { printf nat; return 0; }
    _vm_known=0
    if [ -n "${3:-}" ] && [ -r "$3" ]; then
        grep -Eiq '^[[:space:]]*Address[[:space:]]*=[^#]*:' "$3" && { printf nat; return 0; }
        _vm_known=1
    fi
    case "$_vm_t" in
        keep) return 0 ;;
        off) _vm_known=1 ;;
    esac
    # Ни в настройке сети, ни среди живых адресов, ни в файле: решать можно только по тому, что
    # устройство есть и адреса у него нет. Нет и самого устройства — оставляем как есть.
    [ "$_vm_known" = 1 ] || [ -e "$OUT_SYSNET/$2" ] || return 0
    printf off
}

# Поставить скачанный пакет, не оставив роутер без того, что работало.
#
# Порядок здесь — не стиль, а разница между «установка не удалась» и «роутер больше не
# маршрутизирует». `apk del` запускает pre-deinstall снимаемого пакета, а тот
# останавливает и ОТКЛЮЧАЕТ сервис; stop_service движка сносит таблицу nft и вычищает
# ip rule. Пока удаление стояло первым, любой отказ apk add — не та архитектура,
# кончилось место, битый файл — оставлял роутер без движка, без правил и со снятым
# автозапуском, то есть перезагрузка уже не спасала. И всё это в ответ на «обновить»,
# то есть на действие, которое ничего ломать не собиралось (I-049).
#
# Поэтому сначала ставим. Обновление в пределах одного варианта — самый частый путь —
# при этом вообще не проходит через удаление: apk заменяет пакет на месте.
#
# --force-overwrite нужен потому, что расширенный и базовый пакеты движка владеют одним
# /usr/sbin/steer. Но конфликт ИМЁН пакетов (provides/conflicts) он не снимает — вот на
# нём удаление и остаётся законным, уже вторым шагом.
#
# Возвращает код apk; заполняет PKG_OUT (вывод apk) и PKG_REMOVED (снимался ли пакет).
# Закрепления в /etc/apk/world, которые ни на что не указывают.
#
# `apk add ФАЙЛ` (apk 3) записывает в world не «имя», а «имя><хеш файла» — закрепление за этой
# сборкой. Если транзакция оборвалась на середине (на роутере с малым флешем — «No space left on
# device» при распаковке второго пакета набора), world уже записан с хешами НОВЫХ файлов, а в базе
# остались прежние пакеты или не появилось вовсе нового. С этой минуты ЛЮБАЯ команда apk — и наша,
# и чужая, хоть установка zapret — не решается: «unable to select packages: breaks:
# world[steer-core><Q1…]». Воспроизведено на apk 3.0.5 (как на OpenWrt 25.12.5) с tmpfs на 4–5 МБ.
#
# Чиним правкой самого файла, без apk: решатель в таком состоянии отказывает и на `apk add имя`.
# Что делаем с каждой записью «имя><хеш»:
#   - пакета с таким именем нет в базе — запись убирается: она ничего не держит;
#   - пакет стоит, но с другим хешом — становится просто «имя»;
#   - наше имя (аргумент — регулярное выражение имён) — становится «имя» всегда: закрепление за
#     файлом нужно только самой транзакции, дальше оно лишь не даёт apk увидеть пакет в фиде и
#     ломает следующую установку той же версии другой сборки.
# Записи без «><» (в том числе `!имя`) и закрепления чужих пакетов с верным хешом не трогаются.
# Пути — APK_WORLD и APK_DB: стенды подставляют свои.
PKG_OURS='^(steer|steer-.*|libsteer.*|splify2.*|luci-app-splify2|luci-i18n-splify2-.*|steer-box-connector|luci-app-steer-box-connector)$'
pkg_world_heal() {  # [ИМЕНА-ERE]
    [ "$PM" = apk ] || return 0
    _wh_w="${APK_WORLD:-/etc/apk/world}"; _wh_d="${APK_DB:-/lib/apk/db/installed}"
    [ -s "$_wh_w" ] && [ -s "$_wh_d" ] || return 0
    grep -q '><' "$_wh_w" 2>/dev/null || return 0
    grep -q '^P:' "$_wh_d" 2>/dev/null || return 0
    _wh_t="$_wh_w.heal.$$"
    if awk -v ours="${1:-^$}" '
        FILENAME == ARGV[1] {
            if ($0 ~ /^C:/) { c = substr($0, 3); if (p != "") id[p] = c }
            else if ($0 ~ /^P:/) { p = substr($0, 3); if (c != "") id[p] = c }
            if ($0 == "") { c = ""; p = "" }
            next
        }
        {
            i = index($0, "><")
            if (i == 0) { print; next }
            n = substr($0, 1, i - 1); q = substr($0, i + 2)
            if (!(n in id)) next
            if (n ~ ours || id[n] != q) print n; else print
        }' "$_wh_d" "$_wh_w" > "$_wh_t" 2>/dev/null; then
        cmp -s "$_wh_t" "$_wh_w" || mv "$_wh_t" "$_wh_w"
    fi
    rm -f "$_wh_t"
    return 0
}

# Поставить локальный файл тем менеджером, который есть. --force-overwrite понимают оба
# и нужен обоим (см. выше про общий /usr/sbin/steer); --allow-untrusted — только apk:
# у opkg проверки подписи для локального файла нет вовсе, и такого флага он не знает.
#
# Зависимости локального файла оба менеджера ищут в СПИСКАХ ПАКЕТОВ, а на свежей прошивке их
# нет: списки opkg живут в /var, индексы apk — в /var/cache/apk, и то и другое — tmpfs, не
# переживающий перезагрузку. Тогда установка падает на «cannot find dependency ip-full for
# steer» (opkg) или «unable to select packages» (apk — снято с роутера на 25.12), хотя пакет
# скачан и лежит рядом. Списки обновляются и установка повторяется ровно один раз: если
# зависимости нет и после обновления, дело не в списках. Прежняя редакция знала это только
# про opkg: у 1.2.5 зависимостей не было, и ветка apk отказа не встречала; у 26.9 их две.
pkg_add_file() {  # ФАЙЛ... [!ИМЯ...] — одной транзакцией менеджера
    if [ "$PM" = apk ]; then
        pkg_world_heal
        _pa_out="$(apk add --allow-untrusted --force-overwrite "$@" 2>&1)"
        _pa_rc=$?
        if [ "$_pa_rc" != 0 ]; then
            case "$_pa_out" in
                *"unable to select packages"*)
                    pkg_world_heal "$PKG_OURS"
                    apk update >/dev/null 2>&1
                    _pa_out="$(apk add --allow-untrusted --force-overwrite "$@" 2>&1)"
                    _pa_rc=$?
                    _pa_out="$_pa_out
$(s2_t pkg.lists_refreshed "Package lists were empty: refreshed them ({cmd}) and retried" cmd "apk update")"
                    ;;
            esac
        fi
        # Любой исход, в том числе отказ: оборванная транзакция оставляет в world закрепления за
        # файлами, которых в базе нет, — и тогда не ставится уже ничто (см. pkg_world_heal).
        pkg_world_heal "$PKG_OURS"
        printf '%s' "$_pa_out"
        return $_pa_rc
    fi
    _pa_out="$(opkg install --force-overwrite "$@" 2>&1)"
    _pa_rc=$?
    if [ "$_pa_rc" != 0 ]; then
        case "$_pa_out" in
            *"cannot find dependency"*|*"unresolved"*|*"incompatible with the architectures"*)
                opkg update >/dev/null 2>&1
                _pa_out="$(opkg install --force-overwrite "$@" 2>&1)"
                _pa_rc=$?
                    _pa_out="$_pa_out
$(s2_t pkg.lists_refreshed "Package lists were empty: refreshed them ({cmd}) and retried" cmd "opkg update")"
                ;;
        esac
    fi
    printf '%s' "$_pa_out"
    return $_pa_rc
}

# Снять закрепление имени за файлом в /etc/apk/world, ничего не меняя в пакетах: установленный из
# файла пакет записан там как «имя><хеш файла», и пакет-замена под тем же именем (steer-core,
# provides steer) иначе с ним не уживается. У opkg такой записи нет — делать нечего.
# Хватит ли места на флеше под установку этих файлов. 0 — да; 1 — нет, причина в ROOM_ERR.
#
# Проверка — ДО apk, а не на середине распаковки: транзакция, оборванная нехваткой места, оставляет
# в /etc/apk/world закрепления за файлами, которых в базе нет, — и дальше не ставится ничто, хоть
# zapret (жалоба из чата: «breaks: world[steer-core><Q1…]»; лечение — pkg_world_heal). Сколько
# нужно: распакованный пакет весит в 2,1 раза больше своего файла (замер на steer 2.0.4: steer-core
# 1072 КиБ → 2264 КиБ, модули так же), а новые файлы менеджер пишет раньше, чем снимает старые;
# сверху 256 КиБ запаса. Свободное — df оверлея (нет его — корня); df не ответил — не мешаем.
flash_room_ok() {  # ФАЙЛ...
    ROOM_ERR=""
    _fr_need=256
    for _fr_f in "$@"; do
        _fr_sz="$(wc -c < "$_fr_f" 2>/dev/null)"
        _fr_need=$((_fr_need + ${_fr_sz:-0} * 21 / 10 / 1024))
    done
    _fr_free="$({ df -k /overlay 2>/dev/null || df -k / 2>/dev/null; } | awk 'NR == 2 { print $4 }')"
    case "$_fr_free" in ''|*[!0-9]*) return 0 ;; esac
    [ "$_fr_free" -ge "$_fr_need" ] && return 0
    ROOM_ERR="$(s2_t disk.low_room "Not enough flash space: about {need} MB needed, {free} MB free. Free up some space and try again." need "$(( (_fr_need + 1023) / 1024 ))" free "$(( _fr_free / 1024 ))")"
    return 1
}

pkg_unpin() {  # ИМЯ
    pkg_world_heal
    [ "$PM" = apk ] && apk add "$1" >/dev/null 2>&1
    return 0
}

pkg_del() {  # ИМЯ
    pkg_world_heal
    if [ "$PM" = apk ]; then apk del "$1" >/dev/null 2>&1
    else opkg remove "$1" >/dev/null 2>&1
    fi
}

# Строка, которая станет словом shell или частью имени: имена устройств, выходов и
# каналов. Проверяется потому, что импорт делает спеку МЕНЕЕ доверенным источником, а на
# том конце её строки попадают в командные строки: движок подставляет lan_device в
# popen("ip -4 -o addr show ...") без фильтрации (I-003), а этот самый скрипт подставляет
# имена выходов vless в `ubus call service signal {"instance":"vless_$o"}`, а имена их
# устройств — в настройку зоны фаервола (fw_sync). Пока спеку писал только root через
# spec_set, это была теоретическая
# слабость; принятый файл делает её входом.
backup_safe_word() {  # СТРОКА
    case "$1" in
        '') return 1 ;;
        *[!A-Za-z0-9_.:@-]*) return 1 ;;
    esac
    return 0
}

# ЯРЛЫК — то же самое для значений, которые НИКУДА НЕ УЕЗЖАЮТ, кроме экрана.
#
# Зачем понадобилось второе правило. Проверка выше писалась для имён, которые попадают в
# командные строки движка и в текст правил nftables: устройство, выход, файл. Имя КАНАЛА туда
# не попадает — движок строит имена наборов из имени ВЫХОДА (group_set_name), а имя канала
# живёт только в спеке, в его же сообщениях об ошибках и на экране. Но проверялось оно тем же
# правилом, а интерфейс называет новое правило «правило1» кириллицей и подставляет в имя
# названия записей каталога («Заблокированное в РФ»). Итог: архив не восстанавливался у
# любого, кто хоть раз нажал «+» в правилах или «В правило» в каталоге, — то есть почти у
# всех, и отказ звучал как придирка к букве.
#
# Что остаётся запрещённым и почему именно это: кавычки, обратная косая, доллар, обратный
# апостроф и разделители команд. Спека печатается как JSON и читается оболочкой построчно, и
# ровно эти знаки позволяют выйти из строки JSON или из слова оболочки. Управляющие символы
# отсекаются раньше и грубее — проверкой на `\[nrtu]` во всём файле.
#
# Длину здесь не меряем нарочно: значения приезжают сюда через `for v in $(jsonfilter …)`, то
# есть уже разрезанными по пробелам, и померить настоящую длину имени этим способом нельзя.
# Длину ограничивает движок — у него имя канала лежит в буфере фиксированного размера.
backup_safe_label() {  # СТРОКА
    case "$1" in
        '') return 1 ;;
        *'"'*|*'\'*|*'`'*|*'$'*|*"'"*|*';'*|*'&'*|*'|'*|*'<'*|*'>'*) return 1 ;;
    esac
    return 0
}

