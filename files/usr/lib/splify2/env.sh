#!/bin/sh
# Окружение объекта rpcd splify2: швы, пути, настройки и общие функции (fail, call_lock, need_fetch …).
#
# Раньше всё это стояло в шапке диспетчера /usr/libexec/rpcd/splify2. Вынесено файлом, чтобы то же
# окружение получали программы плагинов через lib.sh (splify2-api, раздел «Библиотека для shell-плагинов»):
# плагин, переехавший из каркаса вместе с кодом метода, видит те же переменные и функции, что видел код
# внутри диспетчера. Подключается точкой; своего `exit` нет, при подключении ничего не печатает.
. "${JSHN_SH:-/usr/share/libubox/jshn.sh}"

STEER="${STEER:-/usr/sbin/steer}"
SPEC="${SPEC:-/etc/steer/spec.json}"
# Снимок спеки в момент apply. По нему интерфейс считает «сколько ещё не применено»:
# сравнение с ним переживает перезагрузку страницы, чего память браузера не может.
APPLIED="${APPLIED:-/etc/steer/spec.applied.json}"
LISTS="${LISTS:-/etc/steer/lists}"
# Подписка VLESS. Один файл на роутер, а не по файлу на выход: узлы в подписке уже
# перечислены списком, и выход выбирает из них номером. Два выхода на одну подписку — это
# два узла одного провайдера, и держать для этого две копии файла было бы странно.
SUB="${SUB:-/etc/steer/sub.txt}"
# Остаток трафика подписки, как его назвала панель. Рядом с подпиской, а не в uci: числа
# меняются при каждом обращении к панели, а `uci commit` — это запись в overlay-раздел
# роутера, и держать там счётчик значило бы тереть флеш ради показа на обзоре.
#
# Имя выведено из имени подписки, чтобы при переопределённом SUB оба файла остались рядом.
# Этот же путь перечислен в keep.d движка (steer, /lib/upgrade/keep.d/steer): без него
# обновление прошивки «с сохранением настроек» уносило бы остаток, и обзор показывал бы
# «панель не сообщает остаток» на подписке, которая его сообщает.
SUB_INFO="${SUB_INFO:-${SUB%.txt}.userinfo}"
# Состояние туннелей xsteer: движок пишет по файлу на туннель, «по файлу», а не «по запросу
# процесса», потому что спросить процесс — это запустить процесс, а состояние опрашивают раз в
# пять секунд (см. steer/docs/xsteer.md, раздел про файл состояния). Каталог тот же, что у
# --state-dir движка.
XS_STATE_DIR="${XS_STATE_DIR:-/var/lib/steer}"
# Готовая конфигурация туннеля, собранная обработчиком протокола из uci. Единственный источник,
# из которого печатается ссылка: собирать её здесь во второй раз значило бы завести два места,
# которые превращают uci в настройку, и однажды они разошлись бы.
XS_RUN="${XS_RUN:-/var/run/xsteer}"
# Остальные подписки. Их может быть несколько: у человека бывает две панели, и локации из
# обеих он складывает в один пул. Первая (та, что уже стоит на роутерах) осталась на прежнем
# месте — /etc/steer/sub.txt, — потому что на этот путь ссылаются выходы в спеках, а сдвинуть
# их значило бы сломать маршрутизацию ради переезда файла.
SUBS_DIR="${SUBS_DIR:-/etc/steer/subs}"

SUB_MAIN="$SUB"
SUB_NAME=main

# Где выходит трафик выхода: страна и адрес, как их видит внешняя сторона. Хранится по файлу
# на выход и переживает перезагрузку страницы — интерфейс рисует запомненное сразу, не дожидаясь
# ответа из сети.
#
# В /var/lib, а не в /etc: это измерение, а не настройка, и переписывается оно чаще, чем стоит
# трогать overlay-раздел. Переживать перезагрузку РОУТЕРА ему незачем — узел мог смениться.
GEO_DIR="${GEO_DIR:-/var/lib/splify2}"
# Кто отвечает на вопрос «какой у меня адрес и в какой он стране». cdn-cgi/trace выбран за
# три вещи: отвечает любой узел Cloudflare (то есть ближайший), не требует ни ключа, ни
# учётной записи, и отдаёт две строки простого текста вместо JSON — разбирать его в shell
# нечем и не нужно. Адрес переопределяется: `uci set splify2.main.geo_url=...`.
#
# АДРЕСОМ 1.1.1.1, А НЕ ИМЕНЕМ. По имени сервер на той стороне туннеля (Xray со sniffing
# destOverride) сам ищет адрес сайта и уходит по IPv6, если он у него есть, — и «внешний адрес»
# выхода показывал IPv6 сервера (2a01:…), хотя трафик клиентов выходит и по IPv4. Без имени
# подменять нечего: ответ — тот IPv4, которым выход ходит наружу. Сертификат 1.1.1.1 выдан на
# сам адрес, проверка TLS проходит.
GEO_URL_DEFAULT="https://1.1.1.1/cdn-cgi/trace"
# Чем мерить. Шов для стенда: на машине разработчика curl есть всегда, и роутер без него иначе
# не воспроизвести.
GEO_CURL="${GEO_CURL:-curl}"
# Сколько считать измерение свежим. Узел подписки движок меняет при отказе, но не ежеминутно,
# а каждый опрос — это обращение наружу через туннель со своим таймаутом.
GEO_TTL="${GEO_TTL:-900}"
# Как часто пробовать фоновый замер выхода, у которого свежего замера нет. Без этого опрос
# страницы запускал curl через выход на КАЖДОМ обращении: у узла, который не отвечает, замер не
# удаётся никогда, и роутер стучался к нему без остановки (чат splify2: соединения к узлу почти
# каждые 0,02 с). Минута — дольше самого замера (curl --max-time 8), так что запуски не
# накладываются, и достаточно часто, чтобы оживший узел показал страну без ручной проверки.
GEO_RETRY="${GEO_RETRY:-60}"
# Сервис и файл описания системы — абсолютные пути, поэтому подменить их заглушкой в
# PATH нельзя, а стенду нужны оба: через первый идёт вся установка движка, по второму
# выбирается архитектура пакета.
INITD="${INITD:-/etc/init.d/steer}"
RPCD_INITD="${RPCD_INITD:-/etc/init.d/rpcd}"
# Команда полного удаления следов (метод purge) и пауза перед её запуском — швы для стендов.
PURGE_BIN="${PURGE_BIN:-/usr/sbin/splify2-purge}"
PURGE_DELAY="${PURGE_DELAY:-2}"
PURGE_LOG="${PURGE_LOG:-/tmp/splify2-purge.log}"
OPENWRT_RELEASE="${OPENWRT_RELEASE:-/etc/openwrt_release}"
fail() { json_init; json_add_boolean ok 0; json_add_string error "$1"; json_dump; exit 0; }

# Единственный способ скачать: сначала во временный файл, потом переименовать. Иначе
# оборванная загрузка оставляет на месте рабочего списка обрубок, и канал начинает
# маршрутизировать половину.
# Скачивание живёт отдельным файлом: его же подключает splify2-update-lists, а обход
# закрытого издателя (splify2#15) обязан быть у обеих половин одинаковым — иначе каталог
# открывается, а обновление списков молчит. Путь швом, как и у jshn: на машине
# разработчика этого файла нет, стенд подставляет свой.
FETCH_TIMEOUT=${FETCH_TIMEOUT:-60}
# Подключается ЛЕНИВО — группой методов, которой оно нужно (см. /usr/lib/splify2/rpcd): круг
# опроса и чтение спеки уходят выше, а из остальных методов скачивание нужно половине.
need_fetch() { [ "${_fetch_loaded:-}" = 1 ] || { . "${FETCH_SH:-${SPLIFY2_LIBDIR:-/usr/lib/splify2}/fetch.sh}"; _fetch_loaded=1; }; }
# Где лежат группы методов. Швом — стенд подставляет каталог репозитория.
# Каталог библиотек пакета (env.sh, spec.sh, ext.sh, lib.sh, methods.tsv) и группы методов рядом с ним.
# Стенды подставляют только RPCD_LIB: каталог библиотек выводится из него.
RPCD_LIB="${RPCD_LIB:-${SPLIFY2_LIBDIR:-/usr/lib/splify2}/rpcd}"
SPLIFY2_LIBDIR="${SPLIFY2_LIBDIR:-${RPCD_LIB%/rpcd}}"
# Расширения каркаса (splify2-api): подключаются лениво тем, кому нужны, — как need_fetch.
# Возврат 1 — файла нет (пакет собран не целиком): вызывающий обходится без расширений, а не умирает на `.`.
need_ext() {
    command -v ext_rebuild >/dev/null 2>&1 && return 0
    _ne_f="${EXT_SH:-${RPCD_LIB%/rpcd}/ext.sh}"
    [ -r "$_ne_f" ] || return 1
    . "$_ne_f"
}


# ОБХОД DPI (zapret) НЕ ПОДДЕРЖИВАЕТСЯ: ядро отвергает `kind: zapret`, а такие выходы прежних спек
# при обновлении убирает spec_heal_zapret. Шифрованный DNS — встроенный резолвер ядра
# (`dns.upstreams` в спеке v2: DoH, DoT, DoQ, обычный DNS, выход `out`, bootstrap).
# Чужие установленные zapret / Zapret Manager и https-dns-proxy мы не снимаем и не читаем:
# это настройка человека.
#
# ---- идентификатор устройства для панели подписки (HWID) ----------------------------
#
# Считает его ДВИЖОК (`steer sub-hwid`), а не этот файл. Почему так — в
# steer/src/ext/subfetch.c: идентификатор выводится из MAC-адреса шестнадцатеричным хешем, а
# в оболочке для этого приходилось звать внешние `sha256sum`/`md5sum` и обходить каталог
# устройств глобом. Движок и хеширует сам (mbedtls у него в руках), и порядок портов задаёт
# сортировкой, а не порядком обхода каталога — то есть отвечает на тот же вопрос, но без
# второй реализации и с проверкой стендом.
#
# Здесь остаётся один вызов и его кэш на время работы метода: sub_list зовёт идентификатор
# один раз на весь ответ, а sub_info и sub_set — по разу, и лишний запуск движка на каждое
# обращение был бы платой за неменяющееся число.
HWID_CACHED=""

# Каталог устройств для перечня СЕТЕЙ КЛИЕНТОВ (метод client_nets, splify2#16). Швом, потому
# что стенд подставляет туда свои наборы устройств, — и отдельным именем от OUT_SYSNET ниже
# по той же причине, которая названа у него: у каждого шва своя подделка.
SYSNET="${SYSNET:-/sys/class/net}"

# И тот же каталог для перечня устройств ВЫХОДА (метод devices) — отдельным именем, а не
# общим с SYSNET: у каждого шва своя подделка, и один общий означал бы, что проверка одного
# пути ломает другой. Здесь подделываются туннельные устройства.
OUT_SYSNET="${OUT_SYSNET:-/sys/class/net}"

# Скачать подписку и разобрать, что ответила панель, — ОДНИМ вызовом движка.
#
# Всё, что раньше стояло здесь, переехало в steer sub-fetch: заголовки запроса с
# идентификатором устройства, разбор ответных заголовков, base64 названия подписки,
# арифметика остатка трафика, повтор за другим форматом. Причина — в шапке
# steer/src/ext/subfetch.c; коротко: каждый из этих шагов упирался в то, чего у оболочки нет,
# и потому держался второй реализацией того, что у движка уже было готово. Число пригодных
# узлов, по которому решается «не заглушка ли это», оболочка вообще узнавала регулярным
# выражением из JSON отдельного запуска движка — то есть решение принималось по пересказу
# нашего же ответа.
#
# Здесь остались учёт настройки (какая подписка, где её файлы, что в uci) и передача ответа
# движка наверх. Ответ разбирается jsonfilter-ом по полям, а не пересобирается: второй раз
# описать то же состояние — значит однажды описать его иначе.
SUB_ANSWER=""

# Зона фаервола для устройств, которые движок создаёт сам (выходы kind=vless).
#
# Зачем это здесь. fw4 отвергает форвардинг на устройство, не входящее ни в одну зону:
# политика цепочки forward — drop, и клиент получает «Operation not permitted» ещё до
# того, как пакет доберётся до туннеля. Проверено с настоящего клиента, а не выведено.
#
# Почему этого не делает движок. В nftables вердикт accept в своей базовой цепочке
# завершает только ЕЁ: пакет всё равно доходит до цепочки fw4 и там отбрасывается. То
# есть «разрешить заранее» из отдельной таблицы невозможно в принципе, и единственный
# способ — попасть в зону. А зоны — это uci, то есть управляющий слой. Движок про это
# честно предупреждает («not mentioned by the firewall at all»), но починить не может.
#
# Имена зон и их политики — ниже, у FW_ZONES.

# Файл настройки uci. Пакет его не кладёт, а `uci set` в несуществующий файл молча ничего не
# делает — ссылка подписки «сохранялась» и пропадала, причём метод отвечал ok. Тихая потеря
# настройки хуже отказа, поэтому файл заводится здесь.
#
# `touch`, а не `: > файл`, и это не вкус: отказ перенаправления у СПЕЦИАЛЬНОЙ встроенной
# команды завершает оболочку целиком (так требует POSIX и так делает ash). То есть там, где
# каталога нет или на overlay кончилось место, метод умирал БЕЗ ОТВЕТА вовсе — ни ok, ни
# ошибки, и интерфейс показывал «нет ответа» на пустом месте. Урок был записан в запуске 46 у
# backup_put и там же исправлен, а два других места остались с прежней строкой: sub_set и
# ui_set. Теперь оно одно на все три, потому что три копии одного правила — это три места,
# где его можно забыть по-разному.
UCI_SPLIFY2="${UCI_SPLIFY2:-/etc/config/splify2}"
# Расписка: что в фаерволе сделали МЫ, а что было до нас.
#
# Файл, а не пометка в самой зоне: fw4 на незнакомую опцию в секции ругается («specifies
# unknown option») при каждой перезагрузке правил, и человек читал бы это как дефект. А судить
# по одному имени нельзя: зону с тем же именем мог сделать руками и человек — тогда она его.
#
# Записи двух видов, и вторая не менее важна первой:
#   zone ЗОНА           — зону создали мы, значит нам её и убирать;
#   dev ЗОНА УСТРОЙСТВО — это устройство в эту зону добавили мы.
#
# Учёт ПО КАЖДОМУ устройству нужен затем же, зачем и учёт зоны: в нашу зону человек мог руками
# положить своё устройство, а правило «убрать всё, чего нет в спеке» вынесло бы его молча.
FW_OWNED="${FW_OWNED:-/etc/splify2/fw-owned}"

# ВСЕ ВЫХОДЫ СТОЯТ В ОДНОЙ ЗОНЕ — steer_zone, БЕЗ masq (решение владельца 2026-10-12).
#
# Зона нужна только затем, чтобы fw4 пропускал транзит: политика forward зоны действует лишь
# внутри неё, а устройство без зоны отвергается. Трансляцию IPv4-адресов теперь делает само ядро
# steer в своей таблице (цепочка postrouting_nat4 таблицы inet steer) для видов, которым она
# нужна: interface, awg, члены WARP; IPv6 — по ключу спеки `ipv6` (nat — подмену ставит ядро).
# Поэтому зону с masq мы больше не заводим: два masq (fw4 и ядра) подменяли бы адрес дважды.
#
# Прежние зоны steer_vless (masq 0) и steer_iface (masq 1) слиты в steer_zone: fw_zone_migrate
# убирает заведённые нами (по расписке) раньше, чем синхронизируется новая, — устройство в двух
# зонах fw4 не прощает. Одноимённые зоны человека не трогаются.
#
# ВТОРАЯ ЗОНА — steer_clients, и она не про выход, а про ВХОД. Устройства, которые спека
# называет клиентами, бывают без зоны вовсе: так поднимаются tailscale0 и интерфейс сервера
# WireGuard, заведённый мастером OpenWrt. fw4 роняет такой интерфейс дважды — `forward`, то
# есть маршрутизации через нас нет совсем, и `input`, то есть до роутера с него не доходит
# ничего, включая завёрнутый нами DNS (заворот делает DNAT на адрес самого роутера, дальше
# пакет идёт через `input`). Снаружи это «выбрал tailscale0 в клиентах — правила стоят, а DNS
# не подхватывает». Второе поле `clients` — не вид выхода, а признак этой ветки в fw_zone_sync;
# устройства ей даёт fw_client_devices_unzoned, NAT не нужен.
#
# СТОИТ ПЕРВОЙ, и это не вкусовщина: пробросы «зона клиентов -> зона туннеля» заводит
# синхронизация ЗОНЫ ТУННЕЛЯ, спрашивая fw_client_zones. Пока зоны клиентов нет, та её не
# назовёт — значит завести её надо раньше, чем синхронизируются зоны туннелей.
#
# В steer_zone идут устройства всех видов: vless и hysteria2 (свой TUN), прокси steer-proxy
# (trojan, shadowsocks, socks, http, vmess), xsteer, warp-masque (туннель MASQUE группы kind: warp,
# TUN модуля steer-warpbox), а также interface и awg. Ядро без steer-warpbox вида warp-masque не
# знает — `steer outputs --kind warp-masque` отвечает отказом, fw_devices_of глушит его и даёт
# пустой список.
FW_ZONES="steer_clients:clients:0 steer_zone:vless,hysteria2,trojan,shadowsocks,socks,http,vmess,xsteer,warp-masque,interface,awg:0"

# Релизы GitHub: версия, которой ставится пакет, и НАЗВАНИЕ, которым выпуск называют.
#
# Это две разные строки, и разные они по необходимости. Версия участвует в имени файла пакета
# (`luci-app-splify2-26.9-1_noarch.apk`) и в теге (`v26.9`), поэтому в ней могут быть только
# цифры и точки — пробелу там места нет ни у apk, ни у opkg, ни в URL. А выпуск называется
# «26.9 Andromeda»: так он подписан на странице релизов и так о нём говорят.
#
# Пока бэкенд отдавал одни числа, список версий не сходился ни со страницей релизов, ни с
# разговором о выпуске: человек читал «Обновить до 26.9», а искал «Andromeda». Теперь версия
# и название едут рядом, сравнение по-прежнему идёт по числам, а установка — по версии.
#
# Отбор версий тот же, каким установка версию отвергает: тег с суффиксом («0.9.5-rc1»,
# «nightly») иначе доезжает до выпадающего списка, встаёт первым — то есть помечается
# «свежая» — и получает отказ собственного бэкенда при нажатии «Установить» (I-052). Число
