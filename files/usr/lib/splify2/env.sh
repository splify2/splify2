# Какой менеджер пакетов на этом роутере.
#
# Определяется, а не предполагается: релизы обоих проектов теперь содержат и .apk, и
# .ipk, установщик ставит через тот, что есть, — и бэкенд обязан уметь ровно то же.
# Иначе на OpenWrt 23.05 карточка движка показывала бы пустую версию, «Установить»
# возвращало бы пустое сообщение об ошибке (apk нет, rc 127, вывод пуст), а
# самообновление интерфейса не работало бы вовсе.
#
# Единожды на запуск скрипта: ниже это спрашивают трижды.
# PM_FIXTURE — шов для стенда: на машине разработчика есть только заглушки, и обе сразу,
# поэтому иначе ветка opkg (а именно на ней и случаются беды с зависимостями) не проверяется
# никогда. На роутере переменной нет, и всё решает наличие менеджера.
if [ -n "${PM_FIXTURE:-}" ]; then PM="$PM_FIXTURE"
elif command -v apk >/dev/null 2>&1; then PM=apk
elif command -v opkg >/dev/null 2>&1; then PM=opkg
else PM=none
fi



# ПОРЯДОК ПЕРЕНАПРАВЛЕНИЙ У `wc -c`. Ниже везде `wc -c 2>/dev/null < файл`, а не
# `wc -c < файл 2>/dev/null`, и это не вкус.
#
# Оболочка применяет перенаправления СЛЕВА НАПРАВО и делает это САМА, до запуска команды.
# В написании `< файл 2>/dev/null` отсутствующий файл разбирается тогда, когда stderr ещё
# свой, — и жалобу печатает оболочка, а не `wc`: «cannot open …». Проверено опытом: первая
# форма молчит, вторая говорит вслух.
#
# Куда попадает эта строка. Метод rpcd отвечает СТАНДАРТНЫМ ВЫВОДОМ, и жалоба уезжает
# рядом с ответом — в журнал rpcd, а на части сборок и клиенту, который ждёт JSON.
# Значение при этом уцелело бы (`|| echo 0`), поэтому находка и прожила долго: ответ верный,
# а рядом мусор, которого никто не искал.
#
# Там, где `|| echo 0` не было вовсе (sub_info, backup_get, backup_put), цена выше: между
# проверкой существования и чтением файл может исчезнуть, и тогда в `json_add_int` уезжает
# ПУСТАЯ строка — то есть уже не мусор рядом с ответом, а битый JSON вместо ответа.
#
# Вторая половина той же находки (I-085) — `: > файл` в несуществующем каталоге, которое
# завершает ash целиком, — закрыта раньше: файл настройки заводит uci_file, и стенд следит,
# чтобы перенаправление не вернулось.

# Замок метода (см. ниже, в `call`). Держится до конца процесса: fd 9 закрывается вместе с ним.
# Вложенный вызов того же объекта (spec_heal зовёт apply) замок уже держит родитель, и ждать его у
# потомка значило бы ждать самого себя, — об этом говорит SPLIFY2_LOCK_HELD.
# Нет flock или каталога замков — работаем без замка: хуже прежнего от этого не будет.
call_lock() {  # ИМЯ
    case " ${SPLIFY2_LOCK_HELD:-} " in *" $1 "*) return 0 ;; esac
    command -v flock >/dev/null 2>&1 || return 0
    _cl_dir="${SPLIFY2_LOCK_DIR:-/var/lock}"
    mkdir -p "$_cl_dir" 2>/dev/null
    # exec с недоступным файлом завершает ash целиком, поэтому каталог проверяется заранее.
    [ -d "$_cl_dir" ] && [ -w "$_cl_dir" ] || return 0
    exec 9>"$_cl_dir/splify2-$1.lock"
    _cl_n=0
    until flock -n 9 2>/dev/null; do
        _cl_n=$((_cl_n + 1))
        # Ждём минуту, а не весь срок вызова rpcd (120 с): ждавший сто секунд и начавший свою правку
        # был бы убит rpcd посреди записи, а отказ «повторите» уже не успел бы прозвучать.
        [ "$_cl_n" -gt "${SPLIFY2_LOCK_WAIT:-60}" ] && fail "другая правка настроек ещё идёт — повторите через минуту"
        sleep 1
    done
    SPLIFY2_LOCK_HELD="${SPLIFY2_LOCK_HELD:-} $1"
    export SPLIFY2_LOCK_HELD
}
